#!/usr/bin/env python3
"""
build/bundle.py

Open replacement for Project Rain's proprietary bundler (excluded from the OSS release).
Produces dist/vanta-v2.lua: one loadstring-able file.

What Rain's bundler evidently did, and what this reproduces (each inferred from how
the OSS source is written, not guessed):

  1. `require("@src/...")` resolves against bundled modules. `require(<Instance>)` (used
     in hooking.lua, struct.lua, a few farms) passes through to Roblox's real require,
     which is also exposed as `base_require`.
  2. src/globals.lua is NOT a module. It declares `local` variables (is_chime,
     parallel_hooks_allowed, lexend, chance_store, loaded_signal, place_name, ...) that
     other files read/assign as upvalues, and nothing ever require()s it. So it is
     inlined at the top level of the bundle, before every module, sharing their scope.
  3. `inline_asset_b96("@assets/<file>")` is a BUILD-TIME macro. Callers decode it with
     EncodingService Base64Decode + DecompressBuffer(Zstd), so each call is replaced here
     with a string literal of base64(zstd(file)). zstd comes from the system libzstd.
  4. Obfuscator/string macros (LPH_*, STR_TBL_SF_INVOKE) become identity functions,
     since this tree is unobfuscated.

Usage:  python3 build/bundle.py
"""

import base64
import ctypes
import ctypes.util
import os
import re
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(SCRIPT_DIR)
SRC_DIR = os.path.join(REPO_ROOT, "src")
ASSETS_DIR = os.path.join(REPO_ROOT, "assets")
DIST_DIR = os.path.join(REPO_ROOT, "dist")
OUT_PATH = os.path.join(DIST_DIR, "vanta-v2.lua")

GLOBALS_REL = "globals.lua"


# Assets referenced by the source that are NOT in the OSS release. Each call site is
# replaced with a runtime error instead of failing the build - only safe where the
# caller already pcall()s it. Anything missing that isn't listed here fails the build.
#   brayden.png - features/qol/brayden.lua portrait (load_portrait() is pcall'd):
#                 the minigame works, just without the picture.
KNOWN_MISSING_ASSETS = {"brayden.png"}

INLINE_ASSET_RE = re.compile(r'inline_asset_b96\(\s*"@assets/([^"]+)"\s*\)')


# ---------------------------------------------------------------- zstd via libzstd
def _load_zstd():
    name = ctypes.util.find_library("zstd") or "libzstd.so.1"
    lib = ctypes.CDLL(name)
    lib.ZSTD_compressBound.restype = ctypes.c_size_t
    lib.ZSTD_compressBound.argtypes = [ctypes.c_size_t]
    lib.ZSTD_compress.restype = ctypes.c_size_t
    lib.ZSTD_compress.argtypes = [ctypes.c_void_p, ctypes.c_size_t, ctypes.c_void_p, ctypes.c_size_t, ctypes.c_int]
    lib.ZSTD_decompress.restype = ctypes.c_size_t
    lib.ZSTD_decompress.argtypes = [ctypes.c_void_p, ctypes.c_size_t, ctypes.c_void_p, ctypes.c_size_t]
    lib.ZSTD_isError.restype = ctypes.c_uint
    lib.ZSTD_isError.argtypes = [ctypes.c_size_t]
    return lib


_ZSTD = None
_ASSET_CACHE = {}


def encode_asset(rel):
    """base64(zstd(file)), round-trip verified."""
    global _ZSTD
    if rel in _ASSET_CACHE:
        return _ASSET_CACHE[rel]
    path = os.path.join(ASSETS_DIR, rel)
    if not os.path.isfile(path):
        sys.exit("bundle.py: inline_asset_b96 references missing asset: assets/%s" % rel)
    data = open(path, "rb").read()
    if _ZSTD is None:
        _ZSTD = _load_zstd()
    cap = _ZSTD.ZSTD_compressBound(len(data))
    out = ctypes.create_string_buffer(cap)
    n = _ZSTD.ZSTD_compress(out, cap, data, len(data), 19)
    if _ZSTD.ZSTD_isError(n):
        sys.exit("bundle.py: zstd compress failed for %s" % rel)
    comp = out.raw[:n]
    back = ctypes.create_string_buffer(max(len(data), 1))
    m = _ZSTD.ZSTD_decompress(back, len(data), comp, len(comp))
    if _ZSTD.ZSTD_isError(m) or back.raw[:m] != data:
        sys.exit("bundle.py: zstd round-trip mismatch for %s" % rel)
    encoded = base64.b64encode(comp).decode("ascii")
    _ASSET_CACHE[rel] = encoded
    return encoded


def _expand_one(m):
    rel = m.group(1)
    if rel in KNOWN_MISSING_ASSETS and not os.path.isfile(os.path.join(ASSETS_DIR, rel)):
        print("  note: assets/%s isn't in the OSS release - that call errors at runtime (caller pcalls it)" % rel)
        return '__vanta_missing_asset("%s")' % rel
    return '"%s"' % encode_asset(rel)


def expand_inline_assets(content):
    return INLINE_ASSET_RE.sub(_expand_one, content)


# ---------------------------------------------------------------- bundle pieces
PREAMBLE = """--[[
    vanta-v2 bundle - GENERATED by build/bundle.py, do not edit by hand.
    Edit files under src/ (or assets/) and re-run `python3 build/bundle.py`.
]]

-- Obfuscator / string-protection macros: identity, this tree is unobfuscated.
LPH_OBFUSCATED = false;
function LPH_ENCSTR(s) return s end;
function LPH_NO_VIRTUALIZE(fn) return fn end;
function LPH_JIT_MAX(fn) return fn end;
function STR_TBL_SF_INVOKE(s) return s end;

-- Real Roblox require (Instance -> ModuleScript), kept for base_require(...) callers
-- and for plain require(<Instance>) calls, which are passed through below.
base_require = require;

local modules = {};
local loaded = {};
local results = {};

-- Rojo-style require: returns every value the module returns (ui/tabs/*.lua return
-- `function, {name = ...}` and ui/ui.lua reads both), cached after the first call.
local function require(path)
    if typeof(path) ~= "string" then
        return base_require(path);
    end;

    if loaded[path] then
        local r = results[path];
        return table.unpack(r, 1, r.n);
    end;

    local mod = modules[path];
    if not mod then
        error("[vanta] module not found: " .. path .. " (not in this bundle)", 2);
    end;

    loaded[path] = true; -- set before running so a cyclic require returns nil, not recursion
    results[path] = { n = 0 };
    local r = table.pack(mod());
    results[path] = r;
    return table.unpack(r, 1, r.n);
end;

-- Every bundled .lua module, sorted. list_modules("dir/*") returns the modules directly
-- inside src/dir, "dir/**" everything under it - generated from the real tree at build
-- time, so there is no per-pattern manifest to keep in sync.
local all_modules = {
%(ALL_MODULES)s};

function list_modules(pattern)
    local recursive = pattern:sub(-3) == "/**";
    local dir = pattern:gsub("/%%*%%*?$", "");
    local prefix = "@src/" .. dir .. "/";
    local out = {};
    for _, alias in all_modules do
        if alias:sub(1, #prefix) == prefix then
            local rest = alias:sub(#prefix + 1);
            if recursive or not rest:find("/", 1, true) then
                table.insert(out, alias);
            end;
        end;
    end;
    if #out == 0 then
        warn("[vanta] list_modules: nothing matches '" .. tostring(pattern) .. "'");
    end;
    return ipairs(out);
end;

-- Every literal inline_asset_b96 call is replaced at build time. If this runs,
-- something built the call dynamically, which the bundler can't embed.
function inline_asset_b96(path)
    error("[vanta] inline_asset_b96 called at runtime for " .. tostring(path) .. " - must be a literal \\"@assets/...\\" string so build/bundle.py can embed it", 2);
end;

function __vanta_missing_asset(name)
    error("[vanta] asset '" .. tostring(name) .. "' isn't part of the Project Rain OSS release", 2);
end;

-------------------------------------------------------------------------------
-- src/globals.lua (inlined at top level: its locals are shared by every module)
-------------------------------------------------------------------------------
"""

FOOTER = """
return (require("@src/init"));
"""


def alias_for(rel_path):
    stem = os.path.splitext(rel_path)[0]
    return "@src/" + stem.replace(os.sep, "/")


def collect_modules():
    """(alias, abs_path, kind) for every .lua and .json under src/ except globals.lua."""
    entries = []
    for root, _dirs, files in os.walk(SRC_DIR):
        for name in files:
            ext = os.path.splitext(name)[1]
            if ext not in (".lua", ".json"):
                continue
            abs_path = os.path.join(root, name)
            rel_path = os.path.relpath(abs_path, SRC_DIR)
            if rel_path == GLOBALS_REL:
                continue
            entries.append((alias_for(rel_path), abs_path, ext[1:]))
    entries.sort()
    seen = {}
    for alias, abs_path, _ in entries:
        if alias in seen:
            sys.exit("bundle.py: two files map to %s: %s and %s" % (alias, seen[alias], abs_path))
        seen[alias] = abs_path
    return entries


def lua_long_string(text):
    """Wrap text in a Lua long bracket whose level doesn't occur in the text."""
    level = 0
    while ("]" + "=" * level + "]") in text:
        level += 1
    eq = "=" * level
    # a leading newline right after the opening bracket is dropped by Lua, so add one
    return "[" + eq + "[\n" + text + "]" + eq + "]"


def read_src(path):
    with open(path, "r", encoding="utf-8") as f:
        content = f.read()
    content = expand_inline_assets(content)
    if not content.endswith("\n"):
        content += "\n"
    return content


def main():
    os.makedirs(DIST_DIR, exist_ok=True)
    entries = collect_modules()
    lua_aliases = [a for a, _, kind in entries if kind == "lua"]
    all_modules = "".join('    "%s",\n' % a for a in lua_aliases)

    parts = [PREAMBLE % {"ALL_MODULES": all_modules}]
    parts.append("do end;\n")  # statement boundary before inlined code
    parts.append(read_src(os.path.join(SRC_DIR, GLOBALS_REL)))
    parts.append("\n")

    for alias, abs_path, kind in entries:
        parts.append('modules["%s"] = function()\n' % alias)
        if kind == "lua":
            parts.append(read_src(abs_path))
        else:
            with open(abs_path, "r", encoding="utf-8") as f:
                text = f.read()
            parts.append('return game:GetService("HttpService"):JSONDecode(%s);\n' % lua_long_string(text))
        parts.append("end;\n\n")

    parts.append(FOOTER)
    bundle = "".join(parts)

    leftover = INLINE_ASSET_RE.findall(bundle)
    if leftover:
        sys.exit("bundle.py: unexpanded inline_asset_b96 calls remain: %r" % leftover)

    with open(OUT_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write(bundle)

    n_json = sum(1 for _, _, k in entries if k == "json")
    print("Bundled %d lua + %d json modules + inlined globals.lua, embedded %d assets -> %s (%d bytes)" % (
        len(lua_aliases), n_json, len(_ASSET_CACHE), OUT_PATH, len(bundle.encode("utf-8"))))


if __name__ == "__main__":
    main()
